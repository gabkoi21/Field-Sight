"""Seed 20 deterministic submissions for dashboard testing.

The script is idempotent: rerunning it reuses rows with stable external IDs.
It targets the first active organization and its first active/draft project.
"""

from __future__ import annotations

from datetime import UTC, datetime, timedelta

from sqlmodel import Session, select

from app.db.session import get_engine
from app.models.identity import Organization, OrganizationMembership, Role, User
from app.models.operations import FieldAssignment, KoboConnection, Project, Submission

TOTAL_SUBMISSIONS = 20
ENUMERATORS = (
    ("Amara Field", "amara.field@example.com", "test_seed_amara", "TEST-SEED-001", 8),
    ("Joseph Data", "joseph.data@example.com", "test_seed_joseph", "TEST-SEED-002", 7),
    ("Musu Quality", "musu.quality@example.com", "test_seed_musu", "TEST-SEED-003", 5),
)
LOCATIONS = ("Monrovia Central", "Paynesville", "Sinkor", "Gardnersville")


def first_or_fail[T](items: list[T], label: str) -> T:
    if not items:
        raise RuntimeError(f"No {label} found. Create one in the app first, then rerun this script.")
    return items[0]


def get_or_create_user(session: Session, full_name: str, email: str, username: str, employee_id: str) -> User:
    user = session.exec(select(User).where(User.username == username)).first()
    if user:
        return user
    user = User(
        email=email,
        username=username,
        full_name=full_name,
        employee_id=employee_id,
        phone_number="+231-555-0200",
        address="Seed test enumerator",
        notes="Generated by scripts/seed_dashboard_sample_data.py for local dashboard testing.",
        password_hash="seeded-dashboard-sample-user",
    )
    session.add(user)
    session.flush()
    return user


def get_or_create_membership(session: Session, organization: Organization, user: User) -> OrganizationMembership:
    membership = session.exec(
        select(OrganizationMembership).where(
            OrganizationMembership.organization_id == organization.id,
            OrganizationMembership.user_id == user.id,
        )
    ).first()
    if membership:
        return membership
    membership = OrganizationMembership(
        organization_id=organization.id,
        user_id=user.id,
        role=Role.ENUMERATOR,
        is_active=True,
    )
    session.add(membership)
    session.flush()
    return membership


def get_or_create_connection(session: Session, organization: Organization, project: Project) -> KoboConnection:
    connection = session.exec(
        select(KoboConnection).where(KoboConnection.organization_id == organization.id)
    ).first()
    if connection:
        return connection

    creator = first_or_fail(
        session.exec(
            select(User)
            .join(OrganizationMembership, OrganizationMembership.user_id == User.id)
            .where(OrganizationMembership.organization_id == organization.id)
        ).all(),
        "organization user",
    )
    connection = KoboConnection(
        organization_id=organization.id,
        name="Dashboard seed Kobo connection",
        server_url="https://kf.kobotoolbox.org",
        token_encrypted="dashboard-seed-token",
        selected_form_id=project.kobo_form_id or "dashboard-seed-form",
        selected_form_name=project.kobo_form_name or "Dashboard seed form",
        is_verified=True,
        verified_at=datetime.now(UTC),
        created_by_id=creator.id,
    )
    session.add(connection)
    session.flush()
    return connection


def seed() -> None:
    now = datetime.now(UTC)
    created = 0
    reused = 0

    with Session(get_engine()) as session:
        organization = first_or_fail(
            session.exec(
                select(Organization).where(Organization.is_active).order_by(Organization.created_at)
            ).all(),
            "active organization",
        )
        project = first_or_fail(
            session.exec(
                select(Project)
                .where(Project.organization_id == organization.id)
                .order_by(Project.created_at)
            ).all(),
            "project",
        )
        connection = get_or_create_connection(session, organization, project)

        submission_index = 1
        for full_name, email, username, employee_id, count in ENUMERATORS:
            user = get_or_create_user(session, full_name, email, username, employee_id)
            membership = get_or_create_membership(session, organization, user)
            assignment = session.exec(
                select(FieldAssignment).where(
                    FieldAssignment.organization_id == organization.id,
                    FieldAssignment.membership_id == membership.id,
                    FieldAssignment.project_id == project.id,
                )
            ).first()
            if assignment is None:
                session.add(
                    FieldAssignment(
                        organization_id=organization.id,
                        membership_id=membership.id,
                        project_id=project.id,
                        daily_target=6,
                        is_enabled=True,
                    )
                )

            for _ in range(count):
                external_id = f"dashboard-seed-{submission_index:03d}"
                existing = session.exec(
                    select(Submission).where(
                        Submission.project_id == project.id,
                        Submission.external_id == external_id,
                    )
                ).first()
                if existing:
                    reused += 1
                    submission_index += 1
                    continue

                status = "ready"
                if submission_index in {6, 13, 19}:
                    status = "needs_review"
                if submission_index in {11, 20}:
                    status = "invalid"

                location = LOCATIONS[(submission_index - 1) % len(LOCATIONS)]
                submitted_at = now - timedelta(days=(submission_index - 1) % 10, hours=submission_index % 6)
                session.add(
                    Submission(
                        organization_id=organization.id,
                        project_id=project.id,
                        kobo_connection_id=connection.id,
                        kobo_form_id=project.kobo_form_id or "dashboard-seed-form",
                        external_id=external_id,
                        submitted_at=submitted_at,
                        enumerator=full_name,
                        location=location,
                        review_status=status,
                        raw_answers={
                            "seeded": True,
                            "source": "dashboard_sample_seed",
                            "project": project.name,
                            "enumerator": full_name,
                            "household_id": f"DASH-{submission_index:03d}",
                            "location": location,
                            "respondent_age": 18 + (submission_index % 42),
                            "consent": submission_index % 5 != 0,
                        },
                    )
                )
                created += 1
                submission_index += 1

        session.commit()

    print(
        f"Dashboard sample seed complete: {created} created, {reused} reused, "
        f"{TOTAL_SUBMISSIONS} total sample submissions."
    )


if __name__ == "__main__":
    seed()
