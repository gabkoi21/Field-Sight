"""Seed two project enumerators and 50 deterministic test submissions.

This script is idempotent: rerunning it reuses the test accounts, assignments,
and submissions identified by their stable usernames and external IDs.
"""

from __future__ import annotations

from datetime import UTC, datetime, timedelta

from sqlmodel import Session, select

from app.core.security import password_hasher
from app.db.session import get_engine
from app.models.identity import Organization, OrganizationMembership, Role, User
from app.models.phase3 import FieldAssignment, KoboConnection, Project, Submission


ORGANIZATION_NAME = "Community Health Initiative"
ENUMERATOR_PASSWORD = "FieldSightTest2026!"
SEED_SPECS = (
    {
        "project_name": "Community Health Assessment",
        "count": 30,
        "full_name": "Test Enumerator Health",
        "username": "test_enum_health",
        "email": "test.enumerator.health@example.com",
        "employee_id": "TEST-ENUM-001",
        "location": "Monrovia Central",
    },
    {
        "project_name": "Teach For Liberia",
        "count": 20,
        "full_name": "Test Enumerator Education",
        "username": "test_enum_education",
        "email": "test.enumerator.education@example.com",
        "employee_id": "TEST-ENUM-002",
        "location": "Paynesville",
    },
)


def get_or_create_enumerator(session: Session, organization: Organization, spec: dict[str, object]) -> OrganizationMembership:
    username = str(spec["username"])
    user = session.exec(select(User).where(User.username == username)).first()
    if user is None:
        user = User(
            email=str(spec["email"]),
            username=username,
            full_name=str(spec["full_name"]),
            employee_id=str(spec["employee_id"]),
            phone_number="+231-555-0100",
            address=str(spec["location"]),
            notes="Generated by scripts/seed_test_field_data.py for local testing.",
            password_hash=password_hasher.hash(ENUMERATOR_PASSWORD),
        )
        session.add(user)
        session.flush()

    membership = session.exec(
        select(OrganizationMembership).where(
            OrganizationMembership.organization_id == organization.id,
            OrganizationMembership.user_id == user.id,
        )
    ).first()
    if membership is None:
        membership = OrganizationMembership(
            organization_id=organization.id,
            user_id=user.id,
            role=Role.ENUMERATOR,
            is_active=True,
        )
        session.add(membership)
        session.flush()
    return membership


def seed() -> None:
    now = datetime.now(UTC)
    created_submissions = 0

    with Session(get_engine()) as session:
        organization = session.exec(select(Organization).where(Organization.name == ORGANIZATION_NAME)).first()
        if organization is None:
            raise RuntimeError(f"Organization not found: {ORGANIZATION_NAME}")

        connection = session.exec(
            select(KoboConnection).where(KoboConnection.organization_id == organization.id)
        ).first()
        if connection is None:
            raise RuntimeError("A valid Kobo connection is required before seeding submissions.")

        results: list[tuple[str, str, int, int]] = []
        for spec_index, spec in enumerate(SEED_SPECS, start=1):
            project = next(
                (
                    item
                    for item in session.exec(
                        select(Project).where(Project.organization_id == organization.id)
                    ).all()
                    if item.name.strip() == str(spec["project_name"]).strip()
                ),
                None,
            )
            if project is None:
                raise RuntimeError(f"Project not found: {spec['project_name']}")

            membership = get_or_create_enumerator(session, organization, spec)
            assignment = session.exec(
                select(FieldAssignment).where(
                    FieldAssignment.organization_id == organization.id,
                    FieldAssignment.membership_id == membership.id,
                    FieldAssignment.project_id == project.id,
                )
            ).first()
            if assignment is None:
                session.add(
                    FieldAssignment(
                        organization_id=organization.id,
                        membership_id=membership.id,
                        project_id=project.id,
                        daily_target=5,
                        is_enabled=True,
                    )
                )

            requested_count = int(spec["count"])
            existing_count = 0
            for index in range(1, requested_count + 1):
                external_id = f"test-seed-p{spec_index}-{index:03d}"
                existing = session.exec(
                    select(Submission).where(
                        Submission.project_id == project.id,
                        Submission.external_id == external_id,
                    )
                ).first()
                if existing is not None:
                    existing_count += 1
                    continue

                submitted_at = now - timedelta(days=(index - 1) % 7, hours=index % 8)
                session.add(
                    Submission(
                        organization_id=organization.id,
                        project_id=project.id,
                        kobo_connection_id=connection.id,
                        kobo_form_id=project.kobo_form_id or f"test-form-{spec_index}",
                        external_id=external_id,
                        submitted_at=submitted_at,
                        enumerator=str(spec["full_name"]),
                        location=str(spec["location"]),
                        review_status="ready",
                        raw_answers={
                            "seeded": True,
                            "project": project.name,
                            "enumerator": spec["full_name"],
                            "household_id": f"HH-{spec_index}-{index:03d}",
                            "respondent_age": 18 + (index % 48),
                            "consent": True,
                        },
                    )
                )
                created_submissions += 1

            results.append((project.name, str(spec["full_name"]), requested_count, existing_count))

        session.commit()

    print(f"Seed complete: {created_submissions} new submissions created.")
    for project_name, enumerator_name, requested, existing in results:
        print(f"- {project_name}: {requested} total seed submissions for {enumerator_name} ({existing} already existed)")
    print(f"Test account password: {ENUMERATOR_PASSWORD}")


if __name__ == "__main__":
    seed()
